
    create table carrello_utente_oggetto (
        oggetto_id integer not null,
        utente_id integer not null
    );

    create table disegni (
        id integer not null,
        supporto varchar(255),
        tecnica varchar(255),
        primary key (id)
    );

    create table foto (
        height_resolution integer,
        id integer not null,
        width_resolution integer,
        device varchar(255),
        primary key (id)
    );

    create table illustrazioni (
        data_illustrazione date not null,
        id integer not null,
        oggetto_id integer unique,
        stile varchar(100),
        url_illustrazione varchar(5000) unique,
        primary key (id)
    );

    create table oggetti (
        data_creazione date,
        id integer generated by default as identity,
        is_ai boolean,
        prezzo float(53),
        autore varchar(255),
        categoria varchar(255),
        descrizione varchar(255),
        dimensione varchar(255),
        immagine varchar(255),
        titolo varchar(255),
        primary key (id)
    );

    create table utenti (
        id integer generated by default as identity,
        email varchar(255) unique,
        nome varchar(255),
        password varchar(255),
        primary key (id)
    );

